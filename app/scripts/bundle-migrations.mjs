/**
 * Concatenates every migration, in order, into one file to paste into a fresh
 * Supabase project's SQL editor.
 *
 *   npm run migrations:bundle
 *
 * Why this exists: standing up a second project means applying 0001, 0002 and
 * 0003 by hand, in order, one paste at a time. Doing that by eye is how the
 * wrong thing gets pasted — it already happened once, when a file path went in
 * instead of the file's contents.
 *
 * The numeric filename prefix is what makes a plain sort correct, which is the
 * same property the db-rls CI job relies on. Nothing is written to any
 * database here; this only produces a file.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const MIGRATIONS = join(import.meta.dirname, "..", "supabase", "migrations");
const OUT = join(import.meta.dirname, "..", "supabase", "bundle.generated.sql");

const files = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error(`No .sql files in ${MIGRATIONS}`);
  process.exit(1);
}

const parts = [
  "-- GENERATED by scripts/bundle-migrations.mjs. Do not edit, and do not commit.",
  "-- Every migration in order, for setting up a NEW project in one paste.",
  "--",
  "-- Not for a project that already has some of these applied: each migration",
  "-- is written to be re-runnable, but re-running them all is slower and noisier",
  "-- than applying only the new one.",
  "--",
  `-- Bundled: ${files.join(", ")}`,
  "",
];

for (const file of files) {
  parts.push(
    "-- " + "=".repeat(73),
    `-- ${file}`,
    "-- " + "=".repeat(73),
    "",
    readFileSync(join(MIGRATIONS, file), "utf8").trimEnd(),
    "",
  );
}

const sql = parts.join("\n") + "\n";
writeFileSync(OUT, sql, "utf8");

console.log(`Bundled ${files.length} migrations into:`);
console.log(`  ${OUT}`);
console.log("");
console.log("Paste its contents into the SQL editor of the TARGET project.");
console.log("The last statement reports the table and policy counts to check against.");
